-- Enable PostGIS for geographic calculations
CREATE EXTENSION IF NOT EXISTS postgis;

-- 1. Profiles Table
CREATE TABLE profiles (
    id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
    role TEXT CHECK (role IN ('CUSTOMER', 'HOMEE', 'BUSINESS')) DEFAULT 'CUSTOMER',
    is_verified BOOLEAN DEFAULT FALSE,
    is_shadow BOOLEAN DEFAULT FALSE,
    is_active BOOLEAN DEFAULT FALSE,
    external_source TEXT,
    external_id TEXT,
    rating DECIMAL(3,2) DEFAULT 5.0,
    full_name TEXT,
    avatar_url TEXT,
    identity_verified_at TIMESTAMP WITH TIME ZONE,
    last_known_location GEOGRAPHY(POINT),
    certifications JSONB DEFAULT '[]', -- List of verified skills/docs
    insurance_policy_id TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Services Table
CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment TEXT CHECK (segment IN ('HOME', 'WELLNESS', 'GASTRO_RESCUE', 'OFFICE', 'GARDEN', 'LOCKSMITH', 'PHYSIO_PRO', 'IV_RECOVERY', 'CARE_ASSIST', 'PET_CARE')),
    type TEXT,
    price_per_hour DECIMAL(10,2) NOT NULL,
    required_certification TEXT, -- e.g., 'HEALTH_CARD'
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Jobs Table
CREATE TABLE jobs (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    client_id UUID REFERENCES profiles(id) NOT NULL,
    homee_id UUID REFERENCES profiles(id),
    service_id BIGINT REFERENCES services(id),
    status TEXT CHECK (status IN ('PENDING', 'ACTIVE', 'DONE')) DEFAULT 'PENDING',
    location GEOGRAPHY(POINT) NOT NULL,
    contract_signed_at TIMESTAMP WITH TIME ZONE,
    start_time TIMESTAMP WITH TIME ZONE,
    escrow_status TEXT CHECK (escrow_status IN ('HELD', 'RELEASED', 'DISPUTED')) DEFAULT 'HELD',
    insurance_active BOOLEAN DEFAULT FALSE,
    contract_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- SECURITY: Row Level Security (RLS)
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE services ENABLE ROW LEVEL SECURITY;
ALTER TABLE jobs ENABLE ROW LEVEL SECURITY;

-- Profiles Policies
CREATE POLICY "Public profiles are viewable by everyone" ON profiles FOR SELECT USING (true);
CREATE POLICY "Users can update own profile" ON profiles FOR UPDATE USING (auth.uid() = id);

-- Jobs Policies (The Guard)
-- Customer sees only their own jobs
CREATE POLICY "Customers see own jobs" ON jobs FOR SELECT 
USING (auth.uid() = client_id);

-- HoMee sees jobs in 10km radius if verified
CREATE POLICY "HoMees see nearby jobs" ON jobs FOR SELECT 
USING (
    EXISTS (
        SELECT 1 FROM profiles 
        WHERE id = auth.uid() 
        AND role = 'HOMEE' 
        AND is_verified = TRUE
    )
    AND ST_DWithin(location, (SELECT location FROM profiles WHERE id = auth.uid()), 10000)
);

-- MATCHING FUNCTION (The Engine)
-- Finds verified HoMees within X meters
CREATE OR REPLACE FUNCTION get_nearby_homees(client_location GEOGRAPHY, radius_meters FLOAT)
RETURNS TABLE (
    id UUID,
    full_name TEXT,
    rating DECIMAL,
    distance FLOAT
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        p.id, 
        p.full_name, 
        p.rating,
        ST_Distance(p.location, client_location) as distance
    FROM profiles p
    WHERE p.role = 'HOMEE' 
      AND p.is_verified = TRUE
      AND ST_DWithin(p.location, client_location, radius_meters)
    ORDER BY p.rating DESC, distance ASC;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- WATCHDOG ENGINE: Real-time Arrival Guarantee
-- Triggers alert if HoMee is static 15m before job
CREATE OR REPLACE FUNCTION check_arrival_watchdog()
RETURNS TABLE (job_id UUID, homee_id UUID, alert_type TEXT) AS $$
BEGIN
    RETURN QUERY
    SELECT j.id, j.homee_id, 'STATIC_ALERT'::TEXT
    FROM jobs j
    JOIN profiles p ON j.homee_id = p.id
    WHERE j.status = 'PENDING'
      AND j.start_time <= NOW() + INTERVAL '15 minutes'
      AND ST_Distance(p.last_known_location, j.location) > 500 -- More than 500m away
      AND NOT EXISTS (
          -- Check if they moved in the last 5 minutes
          -- (Conceptual: would require a location_history table for full implementation)
          SELECT 1 FROM profiles WHERE id = j.homee_id AND last_known_location = p.last_known_location
      );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

